"""从页面源码提取字符，生成内嵌字体；修改文案后重新运行。"""
import base64
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parents[1]
source = root / '乐米小奶泡体.ttf'
chars = set(chr(i) for i in range(32, 127))
for path in (root / 'miniprogram').rglob('*'):
    if path.suffix in ('.wxml', '.js', '.json'):
        chars.update(path.read_text(encoding='utf-8'))
options = subset.Options()
font = TTFont(source)
missing = chars - set(map(chr, font.getBestCmap()))
subsetter = subset.Subsetter(options=options)
subsetter.populate(text=''.join(sorted(chars)))
subsetter.subset(font)
from io import BytesIO
buffer = BytesIO()
font.save(buffer)
data = base64.b64encode(buffer.getvalue()).decode('ascii')
output = root / 'miniprogram/styles/font.wxss'
output.write_text('/* Generated by scripts/build-font.py. */\n@font-face {\n  font-family: "LemiMilkFoam";\n  src: url("data:font/ttf;base64,' + data + '") format("truetype");\n  font-style: normal;\n  font-weight: normal;\n}\n', encoding='utf-8')
print('Generated font.wxss: %s bytes; %s characters requested' % (output.stat().st_size, len(chars)))
print('Missing visible characters (system fallback):', ''.join(sorted(c for c in missing if not c.isspace())))
